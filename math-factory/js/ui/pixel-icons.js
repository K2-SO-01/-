  const cache = {};
  /** アイコンを 16×16 の行の配列にする（小さいものは真ん中に置く） */
  Px.rows = function (name) {
    if (cache[name]) return cache[name];
    const src = ICONS[name];
    if (!src) return null;
    const lines = src.split('\n').filter((l) => l.trim());
    const w = Math.max(...lines.map((l) => l.length));
    const left = Math.floor((16 - w) / 2), top = Math.floor((16 - lines.length) / 2);
    const rows = [];
    for (let y = 0; y < 16; y++) {
      const l = lines[y - top];
      rows.push(l === undefined ? '.'.repeat(16) : ('.'.repeat(left) + l.padEnd(w, '.') + '.'.repeat(16)).slice(0, 16));
    }
    cache[name] = rows;
    return rows;
  };
