  /** キャンバスに描く（size はマス目全体の大きさ） */
  Px.draw = function (ctx, name, x, y, size, color) {
    const rows = Px.rows(name);
    if (!rows) return;
    const k = size / 16;
    ctx.save();
    ctx.fillStyle = color || '#b6ff3b';
    rows.forEach((r, yy) => {
      for (let xx = 0; xx < 16; xx++) {
        const c = r[xx];
        if (c === '.') continue;
        ctx.globalAlpha = c === '+' ? 0.45 : 1;
        ctx.fillRect(Math.round(x + xx * k), Math.round(y + yy * k), Math.ceil(k), Math.ceil(k));
      }
    });
    ctx.restore();
  };
