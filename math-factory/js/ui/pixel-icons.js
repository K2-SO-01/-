  // ---------- 画面の絵文字を差しかえる ----------
  const RE = /(?:\p{Extended_Pictographic}|☰)️?(?:‍\p{Extended_Pictographic}️?)*/gu;
  const SKIP = 'SCRIPT,STYLE,TEXTAREA,OPTION,TITLE,INPUT,SELECT';
  Px.has = (t) => { RE.lastIndex = 0; return RE.test(t); };
  function replaceText(node) {
    const text = node.data;
    RE.lastIndex = 0;
    const frag = document.createDocumentFragment();
    let last = 0, m, changed = false;
    while ((m = RE.exec(text))) {
      const key = m[0].replace(/️/g, '');
      const name = Px.EMOJI[key] || Px.EMOJI[Array.from(key)[0]];
      if (!name) continue; // 知らない絵文字はそのまま
      if (m.index > last) frag.appendChild(document.createTextNode(text.slice(last, m.index)));
      frag.appendChild(Px.icon(name, m[0]));
      last = m.index + m[0].length;
      changed = true;
    }
    if (!changed) return;
    if (last < text.length) frag.appendChild(document.createTextNode(text.slice(last)));
    node.parentNode.replaceChild(frag, node);
  }
  function skip(el) {
    for (let e = el; e && e.nodeType === 1; e = e.parentNode) {
      if (SKIP.indexOf(e.nodeName) >= 0 || e.namespaceURI === 'http://www.w3.org/2000/svg') return true;
      if (e.classList && e.classList.contains('px')) return true;
    }
    return false;
  }
  /** root の中の絵文字を、ドット絵アイコンに差しかえる */
  Px.scan = function (root) {
    if (!root) return;
    if (root.nodeType === 3) { if (root.parentNode && Px.has(root.data) && !skip(root.parentNode)) replaceText(root); return; }
    if (root.nodeType !== 1 || skip(root)) return;
    const list = [];
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    for (let n = w.nextNode(); n; n = w.nextNode()) if (Px.has(n.data) && !skip(n.parentNode)) list.push(n);
    list.forEach(replaceText);
    // ツールチップの絵文字は消す（ドット絵にできないので）
    const titled = root.querySelectorAll ? root.querySelectorAll('[title]') : [];
    [root].concat(Array.from(titled)).forEach((e) => { const t = e.getAttribute && e.getAttribute('title'); if (t && Px.has(t)) e.setAttribute('title', t.replace(RE, '').trim()); });
  };
  /** ドット文字（Google Fonts）を、ページの表示を止めずに読み込む。読めない環境では等幅の文字のまま遊べる */
  Px.loadFont = function () {
    if (document.querySelector('link[data-px-font]')) return;
    const l = document.createElement('link');
    l.rel = 'stylesheet'; l.href = 'https://fonts.googleapis.com/css2?family=DotGothic16&display=swap'; l.setAttribute('data-px-font', '1');
    document.head.appendChild(l);
  };
  Px.start = function () {
    Px.loadFont();
    Px.scan(document.body);
    const logo = document.querySelector('.logo');
    if (logo) logo.innerHTML = Px.svg('sigma');
    if (typeof MutationObserver === 'undefined') return;
    new MutationObserver((muts) => {
      for (const m of muts) {
        if (m.type === 'characterData') Px.scan(m.target);
        else m.addedNodes.forEach((n) => Px.scan(n));
      }
    }).observe(document.body, { childList: true, subtree: true, characterData: true });
  };
  if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', Px.start); else Px.start();
  }
